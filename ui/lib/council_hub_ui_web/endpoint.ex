defmodule CouncilHubUiWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :council_hub_ui

  # Wraps Phoenix's call/2 to delete a client-supplied x-council-trusted header
  # (see CouncilHubUiWeb.TrustedScrub). Registered after `use`, so it runs after
  # Phoenix's own before_compile.
  @before_compile CouncilHubUiWeb.TrustedScrub

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_council_hub_ui_key",
    signing_salt: "XOtExJnf",
    same_site: "Lax"
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Agent presence. Authenticated by X-Council-Token when COUNCIL_AUTH_TOKEN is set, see UserSocket. Idle timeout 60 s (the
  # Phoenix default, set explicitly): clients send a heartbeat every 30 s, and a
  # connection silent for 60 s is dropped, which removes its presence entry.
  # Frames are capped at 16 KB (a full 50-room update is about 7 KB). Only the
  # v2 JSON serializer is accepted; no longpoll fallback.
  socket "/socket", CouncilHubUiWeb.UserSocket,
    websocket: [
      # x_headers exposes only `x-` headers, which carries X-Council-Token.
      connect_info: [:x_headers],
      timeout: 60_000,
      max_frame_size: 16_384,
      check_origin: {CouncilHubUiWeb.UserSocket, :allow_origin?, []},
      serializer: [{Phoenix.Socket.V2.JSONSerializer, "~> 2.0.0"}]
    ],
    longpoll: false

  # Runtime-configurable https redirect (COUNCIL_FORCE_SSL) — sits where the
  # compile-time :force_ssl option would put Plug.SSL, ahead of everything else.
  plug CouncilHubUiWeb.Plugs.MaybeForceSsl

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :council_hub_ui,
    gzip: not code_reloading?,
    only: CouncilHubUiWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :council_hub_ui
  end

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug CouncilHubUiWeb.Router
end
